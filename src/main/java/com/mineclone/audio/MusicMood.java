package com.mineclone.audio;

/**
 * На что откликается трек.
 *
 * Один словарь на всё: время суток, место, занятие игрока и меню. На нём
 * говорят и ситуация кадра, и каталог — поэтому «подходит ли трек» сводится
 * к пересечению двух наборов.
 */
public enum MusicMood {
    /** Экраны вне мира, включая загрузку. */
    MENU,
    /** Рассвет и пробуждение. */
    DAWN,
    /** Спокойный день на поверхности. */
    DAY,
    /** Закат. */
    DUSK,
    /** Ночь на поверхности. */
    NIGHT,
    /** Под землёй. */
    CAVE,
    /** Враг идёт на игрока. */
    DANGER,
    /** Игрок уходит далеко. */
    EXPLORE,
    /** Игрок строит. */
    BUILD,
    /** Вечером или ночью под крышей у огня; после возрождения. */
    HOME,
    /** Полёт в творческом режиме. */
    FLIGHT,

    // ---- края -------------------------------------------------------------
    // Биомов одиннадцать, а треков столько не бывает. Край — это группа
    // биомов, звучащих заодно: лес и тайга просят одного, пустыня и бэдлендс
    // другого. Биом сам говорит, в каком он краю, — Biome.musicMood().

    /** Равнина, лес, тайга. */
    WOODS,
    /** Пустыня, бэдлендс, саванна. */
    ARID,
    /** Тундра и гольцы. */
    FROZEN,
    /** Болото. */
    WETLAND,
    /** Океан. */
    SEA,
    /** Вулканические пустоши. */
    ASHEN
}
