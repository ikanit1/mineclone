package com.mineclone.net.connect;

/**
 * Пауза между попытками подключения.
 *
 * <p>Нужна потому, что прежний код сдавался с первого раза: секундный обрыв
 * WebSocket при входе (код закрытия 1006 — самый частый случай на мобильном
 * интернете) рвал все три соединения и выбрасывал игрока в меню. Между тем
 * вторая попытка через полсекунды проходит почти всегда.
 *
 * <p>Пауза растёт: первая попытка почти мгновенная, последняя ждёт несколько
 * секунд. Смысл роста не в вежливости к серверу, а в том, что разные поломки
 * чинятся за разное время — переезд с вышки на вышку укладывается в полсекунды,
 * а переподключение Wi-Fi нет.
 *
 * <p>Класс без времени и без потоков: он только считает попытки и отдаёт
 * задержку. Ждать — дело вызывающего, и ровно поэтому его можно проверить
 * обычным тестом.
 */
public final class Backoff {

    /** Задержки перед второй, третьей и четвёртой попытками, в секундах. */
    public static final float[] DELAYS = { 0.5f, 1.5f, 4f };

    /** Сколько всего попыток: первая плюс по одной на каждую задержку. */
    public static final int ATTEMPTS = DELAYS.length + 1;

    private int attempt;

    /** Номер текущей попытки, считая с единицы. */
    public int attempt() {
        return attempt + 1;
    }

    /** Попытки кончились: дальше пробовать нечего. */
    public boolean exhausted() {
        return attempt >= ATTEMPTS;
    }

    /**
     * Текущая попытка не удалась.
     *
     * @return сколько ждать до следующей; отрицательное — попыток больше нет
     */
    public float failed() {
        if (attempt >= DELAYS.length) {
            attempt = ATTEMPTS;
            return -1f;
        }
        return DELAYS[attempt++];
    }

    /** Начать счёт заново: получилось, или пробуем другую ступень. */
    public void reset() {
        attempt = 0;
    }

    /** Строка для экрана ожидания: «попытка 2 из 4». */
    public String describe() {
        return "попытка " + Math.min(attempt(), ATTEMPTS) + " из " + ATTEMPTS;
    }
}
