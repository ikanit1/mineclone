package com.mineclone.ui;

/**
 * Один экран меню.
 *
 * <p>Экран отвечает на три вопроса и больше ни на что: что он рисует
 * ({@link #draw}), что возвращает ({@link MenuAction}) и от чего зависит —
 * всё, что ему нужно, приходит в конструктор. Игру он не видит.
 *
 * <p>Интерфейс немедленного режима: рисование и разбор ввода — один проход.
 * Ввод кадра экран берёт у темы: {@link MenuTheme#input()}.
 */
public interface Screen {

    /** Нарисовать кадр и разобрать ввод. */
    MenuAction draw(MenuTheme theme);

    /**
     * Нажат Esc. По умолчанию — шаг назад; экран с открытым диалогом или
     * захватом клавиши сначала закрывает их.
     */
    default MenuAction escape() {
        return MenuAction.back();
    }

    /** Экран снова наверху: с дочернего вернулись назад. */
    default void resumed() {
    }

    /** Экран снят со стека насовсем — отпустить текстуры и прочее. */
    default void closed() {
    }
}
