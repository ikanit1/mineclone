package com.mineclone.world;

/**
 * Этап подготовки мира перед входом в игру. Конвейер чанков всегда идёт в
 * этом порядке, и экран загрузки показывает именно его, а не одно безликое
 * число: «87 %» ничего не говорит о том, почему загрузка встала, а
 * «Освещение» — говорит.
 *
 * <p>Порядок объявления значим: {@link #ordinal()} используется как номер
 * этапа при расчёте общего прогресса.
 */
public enum LoadStage {
    /** Чанков вокруг игрока ещё нет — идёт рельеф, пещеры, руды, деревья. */
    GENERATING("Генерация рельефа"),
    /** Чанки есть, разливается свет от неба и источников. */
    LIGHTING("Освещение"),
    /** Свет готов, строятся и загружаются меши. */
    BUILDING("Построение мира"),
    /** Готово — можно отпускать игрока в мир. */
    DONE("Готово");

    public final String title;

    LoadStage(String title) {
        this.title = title;
    }
}
